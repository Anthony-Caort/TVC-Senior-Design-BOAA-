"""
Builds data/ (the files that "Upload Filesystem Image" puts on the ESP32) from the laptop UI folder.

  ../../UI/index.html            -> data/index.html.gz        (gzipped, the ESP32 sends it as-is and the browser unzips)
  ../../UI/lib/leaflet/*.js,css  -> data/lib/leaflet/*.gz     (gzipped, ~150 KB -> ~45 KB)
  ../../UI/lib/leaflet/images/   -> data/lib/leaflet/images/  (copied)
  ../../UI/tiles/15..17          -> data/tiles/15..17         (z18 skipped, too big for the ESP32 flash)
  (generated)                    -> data/config.js            (tells the page it is in WiFi mode, max tile zoom 17)

Runs automatically on every PlatformIO build/upload (extra_scripts in platformio.ini).
Can also be run by hand:  python tools/make_fs_data.py
data/ is generated, never edit it by hand. Edit ../../UI instead.
"""
import gzip
import os
import shutil

MAX_TILE_ZOOM = 17          # highest tile zoom level copied to the ESP32
FS_SIZE_BYTES = 0x1E0000    # LittleFS partition size in no_ota.csv (~1.9 MB)
FS_WARN_FRACTION = 0.85     # warn when the files use more than this much of the partition

CONFIG_JS = """// GENERATED by tools/make_fs_data.py, do not edit. ESP32-served copy of UI/config.js
window.UI_CONFIG = {
  transport: 'wifi',
  maxNativeZoom: %d
};
"""


def gzip_file(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(src, "rb") as f_in, open(dst, "wb") as f_out:
        # mtime=0 so the output only changes when the file content changes
        with gzip.GzipFile(fileobj=f_out, mode="wb", compresslevel=9, mtime=0) as gz:
            gz.write(f_in.read())


def folder_size(path):
    total = 0
    for root, _, files in os.walk(path):
        for name in files:
            total += os.path.getsize(os.path.join(root, name))
    return total


def build(project_dir):
    ui_dir = os.path.normpath(os.path.join(project_dir, "..", "..", "UI"))
    data_dir = os.path.join(project_dir, "data")

    if not os.path.isfile(os.path.join(ui_dir, "index.html")):
        print("make_fs_data: UI folder not found at %s, skipping data/ build" % ui_dir)
        return

    if os.path.isdir(data_dir):
        shutil.rmtree(data_dir)
    os.makedirs(data_dir)

    # Page + Leaflet, gzipped
    gzip_file(os.path.join(ui_dir, "index.html"), os.path.join(data_dir, "index.html.gz"))
    for name in ("leaflet.js", "leaflet.css"):
        gzip_file(os.path.join(ui_dir, "lib", "leaflet", name),
                  os.path.join(data_dir, "lib", "leaflet", name + ".gz"))
    shutil.copytree(os.path.join(ui_dir, "lib", "leaflet", "images"),
                    os.path.join(data_dir, "lib", "leaflet", "images"))

    # Tiles up to MAX_TILE_ZOOM
    tiles_src = os.path.join(ui_dir, "tiles")
    copied_zooms = []
    for zoom in sorted(os.listdir(tiles_src), key=lambda z: int(z) if z.isdigit() else 999):
        if zoom.isdigit() and int(zoom) <= MAX_TILE_ZOOM:
            shutil.copytree(os.path.join(tiles_src, zoom), os.path.join(data_dir, "tiles", zoom))
            copied_zooms.append(int(zoom))

    max_zoom = max(copied_zooms) if copied_zooms else MAX_TILE_ZOOM
    with open(os.path.join(data_dir, "config.js"), "w", newline="\n") as f:
        f.write(CONFIG_JS % max_zoom)

    used = folder_size(data_dir)
    print("make_fs_data: data/ built, tiles z%s, %.0f KB of %.0f KB LittleFS (%.0f%%)"
          % (",".join(str(z) for z in copied_zooms), used / 1024, FS_SIZE_BYTES / 1024, 100.0 * used / FS_SIZE_BYTES))
    if used > FS_SIZE_BYTES * FS_WARN_FRACTION:
        print("make_fs_data: WARNING data/ is close to or over the LittleFS size, the upload may fail. "
              "Lower MAX_TILE_ZOOM or export a smaller area.")


try:
    # Running inside PlatformIO (extra_scripts): SCons provides Import() and env
    Import("env")  # noqa: F821
    build(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    # Running by hand: python tools/make_fs_data.py
    if __name__ == "__main__":
        build(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
